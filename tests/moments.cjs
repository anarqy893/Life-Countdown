const { app, BrowserWindow } = require('electron');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
const factor = Number(process.argv[2] || 1);
app.disableHardwareAcceleration();
app.commandLine.appendSwitch('force-device-scale-factor', String(factor));
(async () => {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'life-moments-'));
  app.setPath('userData', temporary); app.setPath('sessionData', temporary);
  const { defaults } = await import('../src/model.mjs');
  const { estimateOccasions } = await import('../src/moments.mjs');
  const initial = { ...defaults(), birthday: '1986-06-15', lifespan: 80, onboardingStep: 'moments', setupHoursConfirmed: true };
  delete initial.moments; // Older profiles do not have reflections yet.
  const settingsPath = path.join(temporary, 'life-countdown.json');
  await fs.writeFile(settingsPath, JSON.stringify(initial));
  require('../main.cjs');
  const until = async (check, label) => {
    for (let i = 0; i < 150; i++) { if (await check()) return; await pause(30); }
    throw new Error(`Timed out: ${label}`);
  };
  await until(() => BrowserWindow.getAllWindows().length > 0, 'main window');
  const main = BrowserWindow.getAllWindows()[0], run = code => main.webContents.executeJavaScript(code);
  const visible = selector => until(() => run(`!!document.querySelector(${JSON.stringify(selector)})`).catch(() => false), selector);
  const click = async selector => { await visible(selector); await run(`document.querySelector(${JSON.stringify(selector)}).click()`); };
  const saved = async () => JSON.parse(await fs.readFile(settingsPath, 'utf8'));
  const capture = async name => {
    main.showInactive(); await pause(150);
    await fs.mkdir(path.join(__dirname, '../artifacts'), { recursive: true });
    await fs.writeFile(path.join(__dirname, `../artifacts/moments-${name}-${factor}.png`), (await main.webContents.capturePage()).toPNG());
  };
  await visible('#moment-picker');
  assert.equal(await run('document.querySelectorAll("[data-moment-example]").length'), 6, 'signup has six focused examples');
  assert.equal(await run('!!document.querySelector("#moment-review, #moment-more-ideas")'), false, 'signup has no review or more-ideas stage');
  assert.equal(await run('!!document.querySelector(".sidebar")'), false);
  await click('[data-moment-example="0"]'); await visible('.moment-live-result');
  assert.equal(await run('document.querySelectorAll("[data-live-id][open]").length'),1,'first selected activity expands');
  const expected = estimateOccasions(initial.birthday,80,{times:1,years:1});
  assert.equal(await run('Number(document.querySelector(".moment-live-result .occasion-count strong").textContent)'),expected,'bubble immediately shows the default estimate');
  assert.equal(await run('document.querySelectorAll(".moment-live-result .occasion-dots i").length'),expected);
  await run('(() => {const row=document.querySelector("[data-live-id]");row.querySelector("[name=years]").value="2";row.querySelector("[name=years]").dispatchEvent(new Event("input",{bubbles:true}));})()');
  assert.equal(await run('document.querySelector("[data-frequency-years]").textContent'),'years');
  await click('[name="useReferenceAge"]');
  await run('(() => {const row=document.querySelector("[data-live-id]");row.querySelector("[name=untilAge]").value="65";row.querySelector("[name=untilAge]").dispatchEvent(new Event("input",{bubbles:true}));})()');
  assert.equal(await run('Number(document.querySelector(".moment-live-result .occasion-count strong").textContent)'),estimateOccasions(initial.birthday,80,{times:1,years:2,untilAge:65}));
  assert.equal((await saved()).moments,undefined,'experimenting does not save data');
  await capture('live-setup');
  main.unmaximize();await until(()=>!main.isMaximized(),'restore before small window check');
  const originalSize=main.getSize();main.setSize(900,680);await pause(150);
  assert.ok(await run('document.querySelector("main").scrollWidth<=document.querySelector("main").clientWidth+2'),'live signup fits small windows');
  await capture('live-small');main.setSize(...originalSize);
  await run('document.querySelector("#moment-live-form").requestSubmit()');await visible('#guide-finish');
  assert.equal((await saved()).moments[0].untilAge,65);
  await run('location.reload()');await visible('#guide-finish');
  await click('[data-guide-back="moments"]');await visible('[data-live-id]');
  assert.equal(await run('document.querySelector("[name=untilAge]").value'),'65','saved entries reappear with their custom age');
  await click('[data-moment-example="3"]');
  assert.equal(await run('document.querySelectorAll("[data-live-id][open]").length'),1,'second activity collapses the first');
  assert.equal(await run('document.querySelector("[data-live-id][open] summary").textContent'),'Skiing / snowboarding');
  await run('document.querySelector("#moment-custom-form").elements.customName.value=["Family holidays","A special trip"].join(String.fromCharCode(10));document.querySelector("#moment-custom-form").requestSubmit()');
  assert.equal(await run('document.querySelectorAll(".moment-live-result").length'),4,'several custom names can be added in one submission');
  assert.equal(await run('document.querySelector("[data-live-id][open] summary").textContent'),'A special trip','only the final bulk addition expands');
  await click('[data-live-id]:last-child [data-live-remove]');
  assert.equal(await run('document.querySelectorAll(".moment-live-result").length'),3,'custom activity joins the same preview');
  assert.equal(await run('document.querySelectorAll("[data-live-id][open]").length'),1,'custom addition leaves only the new activity expanded');
  assert.equal(await run('document.querySelector("[data-live-id][open] summary").textContent'),'Family holidays');
  await click('[data-live-id]:first-child summary');
  assert.equal(await run('document.querySelectorAll("[data-live-id][open]").length'),1,'opening an earlier activity closes the other one');
  assert.equal(await run('document.querySelector("[data-live-id][open] summary").textContent'),'Swimming in the ocean');
  assert.equal(await run('!!document.querySelector("#moment-form, #moment-batch-form")'),false,'custom addition does not open a separate editor');
  await click('[data-moment-example="3"]');
  assert.equal(await run('document.querySelectorAll(".moment-live-result").length'),2,'clicking a selected bubble removes its preview');
  await click('[data-moment-example="3"]');
  await run('document.querySelector("#moment-custom-form").elements.customName.value=Array.from({length:12},(_,i)=>"Layout experience "+i).join(String.fromCharCode(10));document.querySelector("#moment-custom-form").requestSubmit()');
  assert.ok(await run(`['.moment-live-fields','.moment-live-preview'].every(selector=>{
    const pane=document.querySelector(selector),style=getComputedStyle(pane);
    return style.maxHeight==='none'&&style.overflowY==='visible'&&pane.scrollHeight<=pane.clientHeight+1;
  })`),'activity editors and dot panel grow without internal scrollbars');
  assert.ok(await run('document.querySelector(".moment-live-fields").clientHeight>390'),'activity editor list grows past its former height cap');
  assert.ok(await run('document.querySelector(".moment-live-preview").clientHeight>innerHeight'),'dot panel expands past the viewport as activities are added');
  assert.ok(await run('document.querySelector("main").scrollHeight>document.querySelector("main").clientHeight'),'page provides the single scroll area');
  await run('document.querySelector("main").scrollTop=200');
  await click('[data-moment-example="1"]');
  assert.equal(await run('document.querySelector("main").scrollTop'),200,'adding an example preserves the page reading position');
  await click('[data-moment-example="1"]');
  await run('for(let i=0;i<12;i++)document.querySelector("[data-live-id]:last-child [data-live-remove]").click()');
  assert.equal(await run('document.querySelectorAll(".moment-live-result").length'),3);
  await capture('live-multiple');
  await run('document.querySelector("#moment-live-form").requestSubmit()');await visible('#guide-finish');
  assert.equal((await saved()).moments.length,3);
  assert.deepEqual((await saved()).schedules,initial.schedules);
  await click('#guide-finish');await visible('#what-matters');
  const gridHeight=await run('document.querySelector("#grid").offsetHeight');
  await click('#what-matters');await visible('.moments-collection');
  assert.equal(await run('document.querySelectorAll(".occasion-row").length'),3);
  await click('[data-moment-edit]');await visible('#moment-form');
  assert.equal(await run('document.querySelector("#moment-form").elements.untilAge.value'),'65');
  assert.equal(await run('document.querySelector("[data-frequency-years]").textContent'),'years');
  await run('document.querySelector("#moment-form").elements.times.value="2";document.querySelector("#moment-form").dispatchEvent(new Event("input"))');
  assert.equal(await run('document.querySelector("[data-frequency-times]").textContent'),'times');
  await click('#moment-editor-own');await visible('#moment-batch-form');
  assert.equal(await run('document.querySelectorAll("[data-batch-id]").length'),2,'an individual draft can grow into a batch');
  assert.equal(await run('document.querySelector("[data-batch-id] [name=times]").value'),'2','adding another preserves entered values');
  await run('document.querySelector(".moment-batch-row:last-child [name=name]").value="Watching the northern lights";document.querySelector("#moment-batch-form").requestSubmit()');await visible('.moments-collection');
  assert.equal((await saved()).moments.length,4,'existing edit and new experience save together without duplication');
  await click('#add-moment');await visible('#moment-picker');
  assert.equal(await run('document.querySelectorAll("[data-moment-example]").length'),25,'regular tab keeps the full picker');
  await click('[data-moment-example="2"]');await click('#moment-review');await visible('#moment-form');
  await run('document.querySelector("#moment-form").requestSubmit()');await visible('.moments-collection');
  assert.equal((await saved()).moments.length,5,'regular add still works');
  await capture('shared-panel');
  assert.ok(await run('[...document.querySelectorAll(".occasion-row")].every(row=>{const a=row.querySelector("[data-moment-edit]").getBoundingClientRect(),b=row.querySelector("[data-moment-remove]").getBoundingClientRect();return a.width===b.width&&a.height===b.height;})'),'Edit/Remove dimensions stay matched');
  await click('[data-period="life"]');await visible('#grid');
  assert.equal(await run('document.querySelector("#grid").offsetHeight'),gridHeight);
  assert.equal(await run('!!document.querySelector(".moments-collection")'),false);
  await run('(async()=>{const next=await window.desktop.read();next.lifespan=70;await window.desktop.save(next);})()');
  await run('location.reload()');await visible('#what-matters');await click('#what-matters');await visible('.moments-collection');
  const stored=await saved();
  for(const item of stored.moments){
    const actual=await run('(()=>{const row=[...document.querySelectorAll(".occasion-row")].find(row=>row.querySelector("h2").textContent==='+JSON.stringify(item.name)+');return Number(row.querySelector(".occasion-count strong").textContent);})()');
    assert.equal(actual,estimateOccasions(initial.birthday,70,item),'default and custom horizons remain correct');
  }
  let remaining=await run('document.querySelectorAll(".occasion-row").length');
  while(remaining){await click('[data-moment-remove]');remaining--;await until(()=>run('document.querySelectorAll(".occasion-row").length==='+remaining),'remove saved reflection');}
  assert.equal((await saved()).moments.length,0);
  await visible('#first-moment');await click('#first-moment');await visible('#moment-picker');await click('#moments-back');await visible('#first-moment');
  await click('#first-moment');await click('#moment-own');await visible('#moment-batch-form');
  await run('document.querySelector("[data-batch-id] [name=name]").value="Visiting grandparents";document.querySelector("[data-batch-id] [name=name]").dispatchEvent(new Event("input",{bubbles:true}))');
  await click('#moment-batch-own');
  await run('document.querySelector(".moment-batch-row:last-child [name=name]").value="A special trip";document.querySelector(".moment-batch-row:last-child [name=times]").value="3";document.querySelector("#moment-batch-form").requestSubmit()');await visible('.moments-collection');
  assert.deepEqual((await saved()).moments.map(({name,times})=>({name,times})),[{name:'Visiting grandparents',times:1},{name:'A special trip',times:3}],'custom-only experiences save as one batch');
  console.log('Moments check passed at '+factor+': live signup, inline custom activities, frequency wording, end ages, persistence, full library, editing, and My Life.');
  app.exit(0);
})().catch(error => { console.error(error); app.exit(1); });
