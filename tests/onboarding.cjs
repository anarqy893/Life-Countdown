const { app, BrowserWindow, screen, powerMonitor } = require('electron');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
const factor = Number(process.argv[2] || 1);
app.disableHardwareAcceleration();
app.commandLine.appendSwitch('force-device-scale-factor', String(factor));
const unexpectedQuit = () => { console.error('Onboarding check quit before completion'); app.exit(1); };
app.on('before-quit', unexpectedQuit);

(async () => {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'life-onboarding-'));
  app.setPath('userData', temporary); app.setPath('sessionData', temporary);
  const resuming = process.argv.includes('resume');
  if (resuming) {
    const { defaults } = await import('../src/model.mjs');
    await fs.writeFile(path.join(temporary, 'life-countdown.json'), JSON.stringify({ ...defaults(), birthday: '1990-04-12', onboardingStep: 'allocations' }));
  }
  await app.whenReady();
  const width = Math.floor(1920 / factor), height = Math.floor(1080 / factor);
  const area = { x: 0, y: 0, width, height: height - 40 };
  screen.getPrimaryDisplay = () => ({ workArea: area });
  require('../main.cjs');
  let main;
  async function until(check, label) {
    for (let i = 0; i < 150; i++) { if (await check()) return; await pause(30); }
    throw new Error(`Timed out: ${label}`);
  }
  await until(() => { main = BrowserWindow.getAllWindows()[0]; return main; }, 'main window');
  const run = code => main.webContents.executeJavaScript(code);
  const visible = selector => until(() => run(`!!document.querySelector(${JSON.stringify(selector)})`).catch(() => false), selector);
  const click = async selector => { await visible(selector); await run(`document.querySelector(${JSON.stringify(selector)}).click()`); };
  const saved = async () => JSON.parse(await fs.readFile(path.join(temporary, 'life-countdown.json'), 'utf8'));
  const screenshot = async name => {
    await fs.mkdir(path.join(__dirname, '../artifacts'), { recursive: true });
    main.showInactive(); await pause(200);
    await fs.writeFile(path.join(__dirname, `../artifacts/onboarding-${name}-${factor}.png`), (await main.webContents.capturePage()).toPNG());
  };
  const fits = async () => {
    await pause(200);
    assert.ok(await run(`(() => {
      const grid = document.querySelector('#grid').getBoundingClientRect();
      const wrap = document.querySelector('.grid-wrap').getBoundingClientRect();
      const content = document.querySelector('main');
      return grid.width > 0 && grid.height > 0 && grid.bottom <= wrap.bottom + 2
        && grid.right <= wrap.right + 2 && (document.querySelector('.guide-workspace') || content.scrollHeight <= content.clientHeight + 2);
    })()`), `guided grid fits at ${factor} scale`);
  };
  if (resuming) {
    await visible('#guide-hours');
    assert.equal(BrowserWindow.getAllWindows().length, 1, 'unfinished setup launches only the main window');
    app.emit('second-instance'); await pause(100);
    assert.equal(BrowserWindow.getAllWindows().length, 1, 'repeated launch stays in setup');
    app.removeListener('before-quit', unexpectedQuit);
    app.once('will-quit', () => {
      try {
        assert.equal(BrowserWindow.getAllWindows().length, 0);
        console.log('Onboarding resume check passed: startup restores unfinished setup and closing exits fully.');
      } catch (error) { console.error(error); app.exit(1); }
    });
    main.close(); return;
  }
  await visible('#setup');
  await until(() => main.isMaximized(), 'first setup maximized');
  assert.equal(main.isFullScreen(), false);
  main.unmaximize();
  await until(() => !main.isMaximized(), 'restore default setup size');
  assert.equal(BrowserWindow.getAllWindows().length, 1);
  assert.equal(await run('document.querySelectorAll(".welcome-questions li").length'), 3);
  assert.equal(await run('!!document.querySelector(".sidebar")'), false);
  await run('window.desktop.openWidget()');
  assert.equal(BrowserWindow.getAllWindows().length, 1, 'widget cannot bypass preliminary setup');
  await click('#setup'); await visible('#guide-personalize');
  assert.equal(await run('!!document.querySelector(".sidebar")'), false, 'setup has no navigation sidebar');
  await fits(); await screenshot('example');
  assert.equal(await run('document.querySelector(".timeline-axis-x span:last-child").textContent'), '52');
  assert.ok(await run('[...document.querySelectorAll(".week")].every(cell => getComputedStyle(cell).overflow === "hidden")'), 'square contents are clipped');
  await click('#guide-personalize'); await visible('#profile-form');
  assert.equal(await run('!!document.querySelector("#category-form, [data-opacity]")'), false);
  await run(`(() => { const f = document.querySelector('#profile-form'); f.elements.birthday.value='1990-04-12'; f.requestSubmit(); })()`);
  await visible('#guide-allocate'); await fits(); await screenshot('calendar');
  const calendarPanel = await run('({left:document.querySelector(".guide-chart").offsetLeft,top:document.querySelector(".guide-chart").offsetTop,height:document.querySelector(".guide-chart").offsetHeight})');
  assert.ok((await saved()).schedules.every(s => s.hours.sleep === 0 && s.hours.work === 0));
  await click('#guide-allocate'); await visible('#guide-hours'); await fits();
  assert.equal(await run('document.querySelector(".guide-progress [aria-current=step]").textContent'),'4. Your time');
  assert.deepEqual(await run('({left:document.querySelector(".guide-chart").offsetLeft,top:document.querySelector(".guide-chart").offsetTop,height:document.querySelector(".guide-chart").offsetHeight})'), calendarPanel, 'grid panel stays anchored between personal setup steps');
  assert.equal(await run('getComputedStyle(document.querySelector("#grid")).gridTemplateColumns.split(" ").length'), 52, 'setup keeps 52 weeks per row');
  assert.ok(await run('document.querySelector(".guide-chart").clientHeight >= 640'), 'setup reserves a tall chart instead of squeezing it below the inputs');
  assert.equal(await run('!!document.querySelector("#guide-skip")'), false);
  await run('document.querySelector("#guide-hours").requestSubmit()');
  assert.equal(await run('!!document.querySelector("#guide-hours")'), true, 'blank hours cannot advance');
  await run(`(() => { const f=document.querySelector('#guide-hours'); f.elements.sleep.value='7.5'; f.dispatchEvent(new Event('input')); })()`);
  assert.ok(await run('document.querySelector("#guide-total").textContent.includes("52.5") && !document.querySelector("#guide-hours .error").textContent'), 'sleep previews while work is blank');
  await run(`(() => { const f=document.querySelector('#guide-hours'); f.elements.sleep.value=''; f.elements.work.value='35'; f.dispatchEvent(new Event('input')); })()`);
  assert.ok(await run('document.querySelector("#guide-total").textContent.includes("35 of") && !document.querySelector("#guide-hours .error").textContent'), 'work previews while sleep is blank');
  await run(`(() => { const f = document.querySelector('#guide-hours'); f.elements.sleep.value='7.5'; f.elements.work.value='35'; f.dispatchEvent(new Event('input')); })()`);
  assert.ok(await run('document.querySelector("#guide-total").textContent.includes("87.5")'));
  await click('#guide-add-activity');
  await run(`(() => { const row=document.querySelector('.guide-extra-activity'); row.querySelector('[data-guide-name]').value='Exercise'; row.querySelector('[data-guide-hours]').value='6'; row.dispatchEvent(new Event('input',{bubbles:true})); })()`);
  assert.ok(await run('document.querySelector("#guide-total").textContent.includes("93.5")'), 'added activity updates preview');
  const gridHeight = await run('document.querySelector("#grid").offsetHeight');
  for (let i = 0; i < 7; i++) await click('#guide-add-activity');
  await pause(150);
  assert.equal(await run('document.querySelector("#grid").offsetHeight'), gridHeight, 'additional activities do not shrink the grid');
  assert.ok(await run('document.querySelector(".guide-activity-list").scrollHeight > document.querySelector(".guide-activity-list").clientHeight'), 'additional activity inputs scroll independently');
  assert.ok(await run('document.querySelector(".legend").scrollHeight > document.querySelector(".legend").clientHeight'), 'long category legend scrolls beside the grid');
  for (let i = 0; i < 7; i++) await click('.guide-extra-activity:last-child [data-guide-remove]');
  await click('[data-guide-remove]');
  assert.ok(await run('document.querySelector("#guide-total").textContent.includes("87.5")'), 'removing draft activity restores preview');
  assert.equal((await saved()).schedules[0].hours.sleep, 0, 'preview never saves hours');
  powerMonitor.emit('unlock-screen'); await pause(100);
  assert.equal(await run('document.querySelector("#guide-hours").elements.sleep.value'), '7.5', 'unlock preserves draft');
  await run(`(() => { const f = document.querySelector('#guide-hours'); f.elements.sleep.value='24'; f.dispatchEvent(new Event('input')); f.requestSubmit(); })()`);
  assert.ok(await run('document.querySelector("#guide-hours .error").textContent.includes("168")'));
  await run(`(() => { const f = document.querySelector('#guide-hours'); f.elements.sleep.value='7.5'; f.dispatchEvent(new Event('input')); })()`);
  await screenshot('allocations');
  const setupSize = main.getSize();
  main.setSize(Math.min(900, setupSize[0]), Math.min(680, setupSize[1]));
  await fits();
  assert.ok(await run('document.querySelector("#grid").clientHeight >= 400'), 'smaller windows retain readable squares and scroll vertically');
  assert.ok(await run('document.querySelector("main").scrollWidth <= document.querySelector("main").clientWidth + 2'), 'small setup has no horizontal overflow');
  await screenshot('allocations-small');
  main.setSize(...setupSize); await pause(150);
  await run('location.reload()'); await visible('#guide-hours');
  assert.equal(BrowserWindow.getAllWindows().length, 1, 'reload resumes setup without a widget');
  await click('#guide-add-activity');
  await run(`(() => { const row=document.querySelector('.guide-extra-activity'); row.querySelector('[data-guide-name]').value='Exercise'; row.querySelector('[data-guide-hours]').value='6'; row.dispatchEvent(new Event('input',{bubbles:true})); })()`);
  await run('document.querySelector("#guide-hours").elements.sleep.value="0"; document.querySelector("#guide-hours").elements.work.value="0"; document.querySelector("#guide-hours").requestSubmit()');
  await visible('#moment-picker');
  assert.equal(await run('document.querySelector(".guide-progress [aria-current=step]").textContent'),'5. What matters');
  await click('#moment-skip'); await visible('#guide-finish');
  assert.equal((await saved()).setupHoursConfirmed, true, 'explicit zero hours are valid');
  assert.ok((await saved()).categories.some(c => c.name === 'Exercise'), 'added activity is saved');
  await click('[data-guide-back="moments"]'); await visible('#moment-picker');
  await click('[data-guide-back="allocations"]'); await visible('#guide-hours');
  const beforeBack = await saved();
  await click('[data-guide-back="calendar"]'); await visible('#guide-allocate');
  await click('[data-guide-back="profile"]'); await visible('#profile-form');
  await click('[data-guide-back="example"]'); await visible('#guide-personalize');
  await click('[data-guide-back="welcome"]'); await visible('#setup');
  assert.equal(await run('!!document.querySelector(".sidebar, .overview-summary, .layout-switch")'), false, 'returning to the introduction does not build the dashboard');
  await run('location.reload()'); await visible('#setup');
  const afterBack = await saved();
  for (const key of ['birthday', 'lifespan', 'categories', 'schedules', 'setupHoursConfirmed']) assert.deepEqual(afterBack[key], beforeBack[key], `returning to welcome preserves ${key}`);
  assert.equal(BrowserWindow.getAllWindows().length, 1, 'returning to welcome keeps setup focused');
  await click('#setup'); await visible('#guide-personalize');
  await click('#guide-personalize'); await visible('#profile-form');
  assert.equal(await run('document.querySelector("#profile-form").elements.birthday.value'), beforeBack.birthday, 'saved dates are available when continuing');
  await run('document.querySelector("#profile-form").requestSubmit()'); await visible('#guide-allocate');
  await click('#guide-allocate'); await visible('#guide-hours');
  await run('document.querySelector("#guide-hours").requestSubmit()'); await visible('#moment-picker'); await click('#moment-skip'); await visible('#guide-finish');
  await screenshot('widget');
  assert.ok(await run('document.querySelector("#guide-finish").getBoundingClientRect().bottom <= innerHeight'), 'setup completion is visible without scrolling');
  assert.equal(BrowserWindow.getAllWindows().length, 1, 'widget waits for an explicit request');
  await click('#guide-show-widget');
  await until(() => BrowserWindow.getAllWindows().some(w => w.webContents.getURL().includes('widget=1')), 'optional widget');
  const setupWidget = BrowserWindow.getAllWindows().find(w => w.webContents.getURL().includes('widget=1'));
  await until(() => setupWidget.webContents.executeJavaScript('!!document.querySelector(".hourly-pulse")').catch(() => false), 'first launch pulse');
  await setupWidget.webContents.executeJavaScript('window.desktop.previewEffect("off")');
  setupWidget.hide();
  await click('#guide-finish'); await visible('[data-clock]');
  assert.equal((await saved()).onboardingStep, 'done');
  assert.equal((await saved()).gridView, 'allocations', 'setup finishes on time allocations');
  assert.ok(await run('document.querySelector(".allocation-axis-y").getAttribute("aria-label").includes("Age-equivalent")'));
  assert.ok(await run('!!document.querySelector(".sidebar")'), 'navigation appears after completing setup');
  await click('[data-grid-view="timeline"]'); await visible('.timeline-grid');
  await fits(); await screenshot('timeline');
  assert.ok(await run('document.querySelector(".timeline-axis-y").textContent.includes("Age 0")'));
  await click('[data-period="five"]'); await visible('.timeline-grid');
  await fits();
  assert.ok(await run('document.querySelector(".timeline-axis-y").getAttribute("aria-label").includes("Start date")'), 'custom periods use date axes');
  await click('#settings'); await visible('#profile-form');
  await run('document.querySelector("#profile-form").elements.lifespan.value="130"; document.querySelector("#profile-form").requestSubmit()');
  await visible('.timeline-grid'); await fits();
  await click('#settings'); await visible('#profile-form');
  await run('document.querySelector("#profile-form").elements.lifespan.value="90"; document.querySelector("#profile-form").requestSubmit()');
  await visible('.timeline-grid');
  await click('[data-period="life"]'); await visible('.allocation-axis-x span');
  assert.equal((await saved()).gridView, 'allocations', 'returning to My Life opens allocations');
  await click('[data-grid-view="timeline"]'); await visible('.timeline-grid');
  const widget = BrowserWindow.getAllWindows().find(w => w !== main);
  await widget.webContents.executeJavaScript('document.querySelector("#show-grid").click()');
  await until(() => widget.webContents.executeJavaScript('!!document.querySelector(".allocation-axis-x")'), 'widget allocations');
  await pause(200);
  assert.ok(await widget.webContents.executeJavaScript(`(() => { const grid = document.querySelector('#grid').getBoundingClientRect(), wrap = document.querySelector('.grid-wrap').getBoundingClientRect(); return grid.bottom <= wrap.bottom + 2 && grid.right <= wrap.right + 2 && document.querySelector('.widget').scrollHeight <= innerHeight; })()`), 'widget timeline fits');
  await widget.webContents.executeJavaScript('document.querySelector("[data-widget-view=moments]").click()');
  await until(() => widget.webContents.executeJavaScript('!!document.querySelector(".widget-moments")'), 'widget What matters');
  await visible('.timeline-grid');
  assert.equal((await saved()).gridView, 'timeline', 'widget view leaves the main timeline unchanged');
  await widget.webContents.executeJavaScript('document.querySelector("#show-grid").click()');
  widget.hide();
  await click('#settings'); await visible('#category-form');
  assert.equal(await run('!!document.querySelector("[data-opacity], #launch-at-login")'), false, 'time settings are separate');
  await click('#appearance'); await visible('[data-opacity]');
  assert.equal(await run('!!document.querySelector("#category-form")'), false);
  await click('#help'); await visible('#start-tour');
  assert.ok(await run('document.querySelectorAll(".help-topics details").length >= 6'));
  const before = await saved();
  await click('#start-tour'); await visible('#guide-personalize');
  await click('[data-guide-back="welcome"]'); await visible('#setup');
  await run('location.reload()'); await visible('[data-clock]');
  assert.equal((await saved()).onboardingStep, 'done', 'revisiting the introduction does not reset completed setup');
  await click('#help'); await visible('#start-tour');
  await click('#start-tour'); await visible('#guide-personalize');
  await click('#guide-personalize'); await visible('#profile-form');
  await run('document.querySelector("#profile-form").requestSubmit()'); await visible('#guide-allocate');
  assert.deepEqual((await saved()).schedules, before.schedules, 'replaying does not reset schedules');
  await click('#guide-allocate'); await visible('#guide-hours');
  await run('document.querySelector("#guide-hours").requestSubmit()'); await visible('#moment-picker'); await click('#moment-skip'); await visible('#guide-finish');
  await click('#guide-finish'); await visible('[data-clock]');
  assert.deepEqual((await saved()).schedules, before.schedules);
  await click('#help');
  const beforeReset = await saved();
  await click('#reset-app'); await visible('dialog');
  await click('dialog [data-cancel]');
  assert.deepEqual(await saved(), beforeReset, 'cancelling reset preserves entries');
  assert.equal(BrowserWindow.getAllWindows().length, 2, 'cancelling keeps widget available');
  await click('#reset-app'); await visible('dialog');
  await run('document.querySelector("dialog form").requestSubmit()');
  await visible('#setup');
  const fresh = await saved();
  assert.equal(fresh.birthday, '');
  assert.equal(fresh.onboardingStep, 'welcome');
  assert.equal(fresh.widgetCounterOnly, false);
  assert.equal(fresh.categories.length, 2);
  assert.ok(fresh.schedules.every(s => s.hours.sleep === 0 && s.hours.work === 0));
  assert.equal(BrowserWindow.getAllWindows().length, 1, 'reset closes widget for a fresh first-use experience');
  assert.deepEqual(JSON.parse(await fs.readFile(path.join(temporary, 'widget-positions.json'), 'utf8')), {});
  const backups = await fs.readdir(path.join(temporary, 'backups'));
  assert.equal(backups.length, 1, 'confirmed reset creates one backup');
  const backup = JSON.parse(await fs.readFile(path.join(temporary, 'backups', backups[0]), 'utf8'));
  assert.deepEqual(backup.settings, beforeReset, 'backup retains the previous entries');
  await click('#setup'); await visible('#guide-personalize');
  assert.equal(await run('!!document.querySelector(".sidebar")'), false, 'reset restores the focused introduction');
  await click('#guide-personalize'); await visible('#profile-form');
  assert.equal(await run('document.querySelector("#profile-form").elements.birthday.value'), '', 'reset starts setup with empty entries');
  console.log(`Onboarding check passed at ${factor} scale: focused setup, grid fit, live preview, validation, required entries, resuming, optional widget, settings and replay.`);
  app.exit(0);
})().catch(error => { console.error(error); app.exit(1); });
