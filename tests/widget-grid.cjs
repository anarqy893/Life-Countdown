const { app, BrowserWindow, screen } = require('electron');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
const factor = Number(process.argv[2] || 1);
app.disableHardwareAcceleration();
app.commandLine.appendSwitch('force-device-scale-factor', String(factor));
(async () => {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'life-widget-grid-'));
  app.setPath('userData', temporary); app.setPath('sessionData', temporary);
  const { defaults } = await import('../src/model.mjs');
  const { estimateOccasions } = await import('../src/moments.mjs');
  const state = {...defaults(),birthday:'1989-08-03',onboardingStep:'done',setupHoursConfirmed:true,overviewLayout:'classic'};
  state.gridView='timeline';
  state.moments=[{id:'ocean',name:'Swimming in the ocean',times:1,years:1,untilAge:55},{id:'friend',name:'Seeing a faraway friend',times:1,years:1,untilAge:45},{id:'cottage',name:'Going to the cottage',times:2,years:1,untilAge:null}];
  state.schedules[0].hours = {sleep:8,work:40};
  await fs.writeFile(path.join(temporary,'life-countdown.json'),JSON.stringify(state));
  require('../main.cjs');
  const until = async (check,label) => {for(let i=0;i<150;i++){if(await check())return;await pause(30);}throw new Error('Timed out: '+label);};
  await until(()=>BrowserWindow.getAllWindows().length===1,'widget launch');
  const widget=BrowserWindow.getAllWindows()[0],run=code=>widget.webContents.executeJavaScript(code);
  const visible=selector=>until(()=>run(`!!document.querySelector(${JSON.stringify(selector)})`).catch(()=>false),selector);
  const click=async selector=>{await visible(selector);await run(`document.querySelector(${JSON.stringify(selector)}).click()`);};
  const capture=async name=>{widget.showInactive();await pause(150);await fs.mkdir(path.join(__dirname,'../artifacts'),{recursive:true});await fs.writeFile(path.join(__dirname,`../artifacts/widget-grid-${name}-${factor}.png`),(await widget.webContents.capturePage()).toPNG());};
  await visible('#show-grid');
  const initialArea=screen.getDisplayMatching(widget.getBounds()).workArea;
  const initialBounds=widget.getBounds();
  widget.setPosition(initialArea.x+initialArea.width-initialBounds.width-24,initialArea.y+initialArea.height-initialBounds.height-24);
  const compact=widget.getBounds();
  const resizeOpacities=[],originalSetBounds=widget.setBounds.bind(widget);
  widget.setBounds=(...args)=>{resizeOpacities.push(widget.getOpacity());return originalSetBounds(...args);};
  const started=Date.now();
  await click('#show-grid');await visible('#grid .week');
  await until(()=>widget.getOpacity()===1,'finished grid revealed');
  console.log(`Grid presentation from bottom-right: ${Date.now()-started} ms (includes test polling).`);
  assert.equal(resizeOpacities[0],0,'old counter is concealed before the window moves or resizes');
  assert.equal(widget.isVisible(),true,'transition keeps the same native window visible');
  // An outdated acknowledgement must not expose a newer unfinished frame.
  const prepared=await run('window.desktop.prepareWidgetExpanded(true)');
  assert.equal(widget.getOpacity(),0);
  await run(`window.desktop.presentWidget(${prepared.id-1})`);
  assert.equal(widget.getOpacity(),0,'stale frame cannot reveal the widget');
  await run(`window.desktop.presentWidget(${prepared.id})`);
  assert.equal(widget.getOpacity(),1);
  await run('window.desktop.prepareWidgetExpanded(true)');
  await until(()=>widget.getOpacity()===1,'failed renderer acknowledgement recovers automatically');
  await run('window.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape"}))');
  await until(async()=>await run('!document.querySelector(".widget-expanded")')&&widget.getOpacity()===1,'compact frame revealed');
  assert.deepEqual(widget.getBounds(),compact);
  await click('#show-grid');await visible('#grid .week');
  assert.equal(await run('document.querySelector("#close-widget").getAttribute("aria-label")'),'Collapse grid to counter');
  await click('#close-widget');
  await until(async()=>!await run('!!document.querySelector(".widget-expanded")')&&widget.getOpacity()===1,'grid X returns to counter');
  assert.equal(widget.isDestroyed(),false,'grid X keeps the widget running');
  assert.equal(widget.isVisible(),true,'grid X leaves the counter visible');
  assert.deepEqual(widget.getBounds(),compact,'grid X restores the original counter position and size');
  assert.equal(await run('document.querySelector("#close-widget").getAttribute("aria-label")'),'Close widget','compact X retains its close action');
  await click('#show-grid');await visible('#grid .week');
  await until(()=>widget.getOpacity()===1,'expanded frame ready');
  assert.ok(resizeOpacities.every(opacity=>opacity===0),'both expansion and collapse conceal intermediate bounds');
  const area=screen.getDisplayMatching(widget.getBounds()).workArea;
  assert.equal(widget.getBounds().height,area.height-24,'expanded grid uses the usable screen height');
  assert.equal(await run('getComputedStyle(document.querySelector("#grid")).gridTemplateColumns.split(" ").length'),52,'widget keeps 52 columns even with the original main layout');
  assert.ok(await run(`(async()=>{
    const {calculate,periodFor,squareSegments}=await import('./src/model.mjs');
    const state=await window.desktop.read(),result=calculate(state,periodFor({...state,selected:state.widgetSelected}));
    const groups=result.groups.filter(group=>!(state.hiddenGroups||[]).includes(group.id));
    const total=groups.reduce((sum,group)=>sum+group.hours,0);
    const cells=[...document.querySelectorAll('#grid .week')];
    const number=new Intl.NumberFormat(undefined,{maximumFractionDigits:1});
    return cells.length===Math.ceil(total/168)&&cells.every((cell,i)=>{
      const segments=squareSegments(groups,i,total);
      return cell.title==='Square '+(i+1)+'\\n'+segments.map(segment=>segment.name+': '+number.format(segment.fraction*168)+' hours').join('\\n')
        &&cell.classList.contains('crossed')===segments.every(segment=>segment.id==='elapsed');
    });
  })()`),'optimized squares preserve every tooltip, partial allocation, and lived-week marking');
  const fits=()=>run(`(()=>{
    const grid=document.querySelector('#grid').getBoundingClientRect(),wrap=document.querySelector('.grid-wrap').getBoundingClientRect();
    return grid.right<=wrap.right+1&&grid.bottom<=wrap.bottom+1&&grid.left>=wrap.left&&grid.top>=wrap.top&&document.querySelector('.widget').scrollHeight<=innerHeight+1;
  })()`);
  assert.ok(await fits(),'allocation grid fits');
  assert.ok(await run('document.querySelector("#grid").clientHeight>innerHeight*.75'),'most of the window height is used for squares');
  assert.ok(await run('document.querySelector(".widget-grid-toolbar").getBoundingClientRect().height<60'),'toolbar stays compact');
  assert.equal(await run('!!document.querySelector("[data-clock],.widget-bar")'),false,'expanded view prioritizes the grid');
  await capture('allocations');
  const gridHeight=await run('document.querySelector("#grid").offsetHeight');
  await run(`(async()=>{const next=await window.desktop.read();for(let i=0;i<24;i++)next.categories.push({id:'extra-'+i,name:'Additional meaningful activity '+i,color:'#91a979',unit:'week'});await window.desktop.save(next);})()`);
  await run('location.reload()');await visible('.legend-item[data-group="extra-23"]');await pause(150);
  assert.equal(await run('document.querySelector("#grid").offsetHeight'),gridHeight,'extra categories do not shrink squares');
  assert.ok(await run('document.querySelector(".legend").scrollHeight>document.querySelector(".legend").clientHeight'),'long legend scrolls independently');
  await capture('many-categories');
  await click('[data-widget-view="moments"]');await visible('.widget-occasion-row');
  assert.equal(await run('document.querySelectorAll(".widget-occasion-row").length'),3);
  assert.equal(await run('!!document.querySelector("[data-grid-view=timeline]")'),false,'widget replaces its timeline toggle');
  assert.equal(await run('Number(document.querySelector(".widget-occasion-row .occasion-count strong").textContent)'),estimateOccasions(state.birthday,90,state.moments[0]));
  assert.equal(await run('(async()=>{const current=await window.desktop.read();return current.gridView;})()'),'timeline','widget choice leaves the main view untouched');
  await capture('what-matters');
  await click('#widget-manage-experiences');
  await until(()=>BrowserWindow.getAllWindows().length===2,'open full app');
  const main=BrowserWindow.getAllWindows().find(window=>window!==widget);
  await until(()=>main.webContents.executeJavaScript('!!document.querySelector(".moments-collection")&&document.querySelector("#what-matters").classList.contains("active")').catch(()=>false),'manage opens What matters directly');
  await main.webContents.executeJavaScript('document.querySelector("[data-period=life]").click()');
  await until(()=>main.webContents.executeJavaScript('!!document.querySelector("[data-grid-view=timeline]")'),'main view switch');
  await main.webContents.executeJavaScript('document.querySelector("[data-grid-view=timeline]").click()');
  await until(()=>main.webContents.executeJavaScript('!!document.querySelector(".timeline-grid")'),'main timeline remains available');
  main.hide();
  await run('location.reload()');await visible('.widget-occasion-row');
  assert.equal(await run('document.querySelector("[data-widget-view=moments]").getAttribute("aria-pressed")'),'true','widget view persists across reload');
  await run('(async()=>{const next=await window.desktop.read();for(let i=0;i<24;i++)next.moments.push({id:"test-"+i,name:"Another meaningful experience "+i,times:1,years:2,untilAge:null});await window.desktop.save(next);})()');
  await run('location.reload()');await visible('.widget-occasion-row');
  assert.ok(await run('document.querySelector(".widget-moments-list").scrollHeight>document.querySelector(".widget-moments-list").clientHeight'),'many experiences scroll within the widget');
  await run('document.querySelector(".widget-moments-list").scrollTop=100;window.dispatchEvent(new Event("focus"))');
  assert.equal(await run('document.querySelector(".widget-moments-list").scrollTop'),100,'refresh preserves the reading position');
  await run('(async()=>{const next=await window.desktop.read();next.moments=[];await window.desktop.save(next);})()');
  await run('location.reload()');await visible('.widget-moments-list .occasion-empty');
  assert.ok(await run('!!document.querySelector("#widget-manage-experiences")'),'empty view offers the full app');
  await click('[data-widget-view="allocations"]');await visible('#grid .week');await pause(100);
  assert.ok(await main.webContents.executeJavaScript('!!document.querySelector(".timeline-grid")'),'returning to widget allocations does not switch the main timeline');
  await run('(async()=>{const next=await window.desktop.read();next.lifespan=130;await window.desktop.save(next);})()');
  await run('location.reload()');await visible('#grid .week');await pause(150);
  assert.ok(await fits(),'130-year allocation horizon fits without overflow');
  await run('(async()=>{const next=await window.desktop.read();next.widgetSelected="five";await window.desktop.save(next);})()');
  await run('location.reload()');await visible('#grid .week');await pause(150);
  assert.ok(await fits(),'custom period grid fits');
  await visible('.allocation-axis-x');await pause(150);
  assert.equal(await run('getComputedStyle(document.querySelector("#grid")).gridTemplateColumns.split(" ").length'),52);
  assert.ok(await fits(),'custom allocation grid fits');
  await run('window.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape"}))');
  await until(()=>run('!document.querySelector(".widget-expanded")'),'collapse');
  await until(()=>widget.getOpacity()===1,'collapsed frame revealed');
  assert.deepEqual(widget.getBounds(),compact,'collapse restores the compact position and size');
  console.log(`Widget grid check passed at ${factor}: screen height, large squares, 52 columns, compact toolbar, many categories, What matters, view independence, manage link, custom periods, and restoration.`);
  app.exit(0);
})().catch(error=>{console.error(error);app.exit(1);});
